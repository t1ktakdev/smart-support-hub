"""Playwright browser checks: honest functional checks, not mocked screenshots."""
from pathlib import Path
import json, subprocess, time
from playwright.sync_api import sync_playwright
root = Path(__file__).resolve().parents[1]
results=[]
def check(name, fn):
 try:
  fn();results.append((name,'PASS',''))
 except Exception as e:
  results.append((name,'FAIL',str(e)[:350]))

def equal(a,b): assert a==b,(a,b)
server=subprocess.Popen(['python','-m','http.server','8765','--bind','127.0.0.1'],cwd=root,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
time.sleep(1)
try:
 with sync_playwright() as p:
  browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--allow-file-access-from-files'])
  page=browser.new_page(viewport={'width':1366,'height':900})
  errors=[]
  page.on('pageerror',lambda e:errors.append(str(e)))
  url=(root.as_uri()+'/')
  page.goto(url+'index.html',wait_until='domcontentloaded')
  page.wait_for_timeout(200)
  check('Dashboard opens and KPIs load',lambda: equal(page.locator('#kpiIncidents').inner_text(),'3'))
  check('Five navigation links',lambda: equal(page.locator('nav[aria-label="Основная навигация"] a').count(),5))
  check('Initial SLA percent 67% (2/3)',lambda:equal(page.locator('#kpiSla').inner_text(),'67%'))
  check('JavaScript console has no exceptions',lambda:equal(errors,[]))
  page.goto(url+'incidents.html',wait_until='domcontentloaded')
  before=page.locator('#incidentTable tr').count()
  page.get_by_role('button',name='Зарегистрировать').click()
  check('Empty title rejected',lambda:(equal(page.locator('#incidentTable tr').count(),before),equal('Введите название обращения.' in page.locator('#incidentError').inner_text(),True)))
  page.locator('#incidentTitle').fill('Тестовое обращение с высоким приоритетом')
  page.locator('select[name="priority"]').select_option('high')
  page.get_by_role('button',name='Зарегистрировать').click()
  check('High priority incident created',lambda:(equal(page.locator('#incidentTable tr').count(),before+1),equal('Высокий' in page.locator('#incidentTable tr').first.inner_text(),True)))
  page.locator('#statusFilter').select_option('resolved')
  check('Status filter',lambda:equal(page.locator('#incidentTable tr').count(),3))
  page.locator('#statusFilter').select_option('all')
  page.locator('#incidentSearch').fill('Тестовое обращение')
  check('Search filter',lambda:equal(page.locator('#incidentTable tr').count(),1))
  page.locator('#incidentTable button[data-action="resolve"]').click()
  check('Resolve incident saves timestamp',lambda:equal(page.evaluate('getData("incidents").find(x=>x.title.startsWith("Тестовое" )).status'),'resolved'))
  page.reload(wait_until='domcontentloaded')
  check('localStorage persists after reload',lambda:equal(page.locator('#incidentTable tr').count(),7))
  page.goto(url+'index.html',wait_until='domcontentloaded')
  check('Dashboard reflects resolved incident',lambda:equal(page.locator('#kpiIncidents').inner_text(),'3'))
  page.goto(url+'maintenance.html',wait_until='domcontentloaded')
  page.locator('input[name="title"]').fill('Добавить журнал печати')
  page.locator('select[name="type"]').select_option('perfective')
  page.get_by_role('button',name='Добавить заявку').click()
  check('Perfective request added',lambda:equal(page.locator('#requestTable tr').count(),5))
  page.goto(url+'releases.html',wait_until='domcontentloaded')
  check('Minor SemVer',lambda:equal(page.locator('#nextVersion').inner_text(),'v1.2.0'))
  page.locator('#releaseLevel').select_option('patch')
  check('Patch SemVer',lambda:equal(page.locator('#nextVersion').inner_text(),'v1.1.1'))
  page.locator('#releaseLevel').select_option('major')
  check('Major SemVer',lambda:equal(page.locator('#nextVersion').inner_text(),'v2.0.0'))
  page.goto(url+'deployments.html',wait_until='domcontentloaded')
  check('At least three deployments',lambda:equal(page.locator('#deploymentTable tr').count()>=3,True))
  page.locator('input[name="client"]').fill('Тестовый клиент')
  page.locator('input[name="product"]').fill('Тестовый продукт')
  page.locator('input[name="owner"]').fill('Тест Т.')
  page.locator('input[name="plannedDate"]').fill('2026-12-01')
  page.get_by_role('button',name='Добавить запись').click()
  check('Deployment form',lambda:equal(page.locator('#deploymentTable tr').count(),5))
  page.locator('#themeButton').click()
  old=page.evaluate('document.documentElement.dataset.theme')
  page.reload(wait_until='domcontentloaded')
  check('Theme persistence',lambda:equal(page.evaluate('document.documentElement.dataset.theme'),old))
  check('SLA formula independent tests',lambda:equal(page.evaluate('''(()=>{let t=Date.parse('2026-11-03T09:00:00Z');let i={priority:'critical',status:'new',createdAt:new Date(t).toISOString(),resolvedAt:null};return [getSlaState(i,settings,t+3*3600000),getSlaState(i,settings,t+5*3600000),getSlaState({...i,status:'resolved',resolvedAt:new Date(t+4*3600000).toISOString()}),getSlaState({...i,status:'resolved',resolvedAt:new Date(t+5*3600000).toISOString()})]})()'''),['on_track','breached','met','breached']))
  page.evaluate("localStorage.setItem('ssh.v1.incidents','{corrupted')")
  page.goto(url+'incidents.html',wait_until='domcontentloaded')
  check('Corrupted localStorage falls back to seed',lambda:equal(page.locator('#incidentTable tr').count(),6))
  mobile=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1)
  mobile.goto(url+'index.html',wait_until='domcontentloaded')
  check('Mobile no page overflow',lambda:equal(mobile.evaluate('document.documentElement.scrollWidth <= window.innerWidth'),True))
  mobile.locator('#menuToggle').click()
  check('Mobile navigation opens',lambda:equal('show' in mobile.locator('#sidebar').get_attribute('class'),True))
  mobile.screenshot(path=str(root/'evidence'/'dashboard-mobile-390.png'),full_page=True)
  # Fresh captures with unchanged seed data in a new isolated browser context.
  ctx=browser.new_context(viewport={'width':1366,'height':900})
  cap=ctx.new_page()
  for f,n in [('index.html','01-dashboard'),('deployments.html','02-deployments'),('incidents.html','03-incidents'),('maintenance.html','04-maintenance'),('releases.html','05-releases')]:
   cap.goto(url+f,wait_until='domcontentloaded');cap.wait_for_timeout(400);cap.screenshot(path=str(root/'evidence'/f'{n}-1366.png'),full_page=True)
  tab=browser.new_page(viewport={'width':768,'height':1024})
  tab.goto(url+'index.html',wait_until='domcontentloaded');tab.screenshot(path=str(root/'evidence'/'dashboard-tablet-768.png'),full_page=True)
  check('768px no overflow',lambda:equal(tab.evaluate('document.documentElement.scrollWidth <= window.innerWidth'),True))
  browser.close()
finally:
 server.terminate();server.wait(timeout=8)
report={'browser':'Chromium (Playwright, local HTTP server)','results':[{'test':n,'status':s,'details':d} for n,s,d in results],'passed':sum(s=='PASS' for _,s,_ in results),'failed':sum(s=='FAIL' for _,s,_ in results)}
(root/'tests'/'results.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
(root/'tests'/'RESULTS.md').write_text('# Тестирование браузера\n\n'+'\n'.join(f'- **{s}** {n}'+(f': {d}' if d else '') for n,s,d in results)+'\n',encoding='utf-8')
for n,s,d in results:print(s,n,d)
print('RESULT:',report['passed'],'PASS /',report['failed'],'FAIL')
if report['failed']:raise SystemExit(1)
